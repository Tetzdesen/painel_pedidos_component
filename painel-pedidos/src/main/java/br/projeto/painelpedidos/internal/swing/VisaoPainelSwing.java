    @Override
    public void exibirCampoData(boolean visivel, LocalDate data) {
        atualizandoData = true;
        try {
            if (data != null) {
                seletorData.setValue(Date.from(data.atStartOfDay(ZoneId.systemDefault()).toInstant()));
            }
        } finally {
            atualizandoData = false;
        }
        rotuloData.setVisible(visivel);
        seletorData.setVisible(visivel);
        painelCamposFiltro.revalidate();
    }

    @Override
    public boolean confirmar(String titulo, String mensagem) {
        return JOptionPane.showConfirmDialog(this, mensagem, titulo, JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE) == JOptionPane.YES_OPTION;
    }

    private LocalDate dataDoSeletor() {
        return ((Date) seletorData.getValue()).toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    @Override
    public void exibirMensagem(String mensagem) {
        rotuloMensagem.setText(mensagem == null || mensagem.isEmpty() ? " " : mensagem);
    }

    @Override
    public void exibirErro(String titulo, String mensagem) {
        JOptionPane.showMessageDialog(this, mensagem, titulo, JOptionPane.WARNING_MESSAGE);
    }

    @Override
    public void focarCard(String identificador) {
        CardPedidoPanel card = cardsPorIdentificador.get(identificador);
        if (card == null) {
            return;
        }
        SwingUtilities.invokeLater(() -> {
            card.scrollRectToVisible(new Rectangle(0, 0, card.getWidth(), card.getHeight()));
            card.requestFocusInWindow();
        });
    }

    @Override
    public void maximizar() {
        Window janela = SwingUtilities.getWindowAncestor(this);
        if (janela instanceof Frame quadro) {
            quadro.setExtendedState(quadro.getExtendedState() | Frame.MAXIMIZED_BOTH);
        }
    }

