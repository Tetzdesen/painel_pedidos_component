    /**
     * Verdadeiro enquanto a tela estiver ligada a um Presenter.
     */
    public boolean isLigada() {
        return eventos != DESLIGADA;
    }

    @Override
    public void exibirOpcoesPeriodo(List<String> opcoes, int indiceSelecionado) {
        atualizandoPeriodo = true;
        try {
            comboPeriodo.setModel(new DefaultComboBoxModel<>(opcoes.toArray(String[]::new)));
            comboPeriodo.setSelectedIndex(indiceSelecionado);
        } finally {
            atualizandoPeriodo = false;
        }
    }

    @Override
    public void exibirRaias(List<RaiaViewModel> raias) {
        cardsPorIdentificador.clear();
        for (RaiaViewModel raia : raias) {
            cabecalhos.get(raia.situacao()).setText(raia.titulo());
            JPanel conteudo = conteudosRaias.get(raia.situacao());
            conteudo.removeAll();
            for (CardViewModel card : raia.cards()) {
                CardPedidoPanel painelCard = new CardPedidoPanel(card,
                        CoresPainel.cabecalho(raia.situacao()), this::eventosAtuais);
                cardsPorIdentificador.put(card.identificador(), painelCard);
                conteudo.add(painelCard);
                conteudo.add(Box.createVerticalStrut(12));
            }
            conteudo.revalidate();
            conteudo.repaint();
        }
    }

