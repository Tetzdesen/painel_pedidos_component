    private void montarRaias() {
        for (SituacaoPedido situacao : SituacaoPedido.values()) {
            JPanel raia = new JPanel(new BorderLayout());
            raia.setBackground(CoresPainel.fundoRaia(situacao));

            JLabel cabecalho = new JLabel(situacao.getRotuloRaia() + " (0)");
            cabecalho.setOpaque(true);
            cabecalho.setBackground(CoresPainel.cabecalho(situacao));
            cabecalho.setForeground(CoresPainel.TEXTO_PRINCIPAL);
            cabecalho.setFont(cabecalho.getFont().deriveFont(Font.BOLD, 14f));
            cabecalho.setBorder(BorderFactory.createEmptyBorder(10, 10, 10, 10));
            raia.add(cabecalho, BorderLayout.NORTH);

            PainelRolavel conteudo = new PainelRolavel();
            conteudo.setLayout(new BoxLayout(conteudo, BoxLayout.Y_AXIS));
            conteudo.setBackground(CoresPainel.fundoRaia(situacao));
            conteudo.setBorder(BorderFactory.createEmptyBorder(10, 10, 10, 10));
            JScrollPane rolagem = new JScrollPane(conteudo,
                    JScrollPane.VERTICAL_SCROLLBAR_AS_NEEDED, JScrollPane.HORIZONTAL_SCROLLBAR_NEVER);
            rolagem.setBorder(BorderFactory.createEmptyBorder());
            rolagem.getViewport().setBackground(CoresPainel.fundoRaia(situacao));
            rolagem.getVerticalScrollBar().setUnitIncrement(16);
            raia.add(rolagem, BorderLayout.CENTER);

            cabecalhos.put(situacao, cabecalho);
            conteudosRaias.put(situacao, conteudo);
            areaRaias.add(raia);
        }
    }

